"""Generate GameData/ProcEngines/Data/Propellants.cfg with NASA CEA (pip install cea, NASA Glenn).

Shifting-equilibrium rocket problems, infinite-area combustor. For each propellant the table is indexed by
mixture ratio (O/F by mass), chamber pressure (bar) and supersonic area ratio. Per (O/F, Pc) row we store the
chamber state and, per area ratio, the ideal vacuum Isp, the local static pressure ratio p/Pc and the Mach number.
The C# model interpolates linearly in O/F and in log(Pc), log(eps).

Run:  tools/.venv/Scripts/python tools/gen_propellants.py
"""
import os
import sys
import numpy as np
import cea

G0 = 9.80665
HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "GameData", "ProcEngines", "Data", "Propellants.cfg")

PC = [3, 5, 10, 20, 35, 50, 70, 100, 140, 200, 270, 350]
EPS = [1, 1.5, 2, 3, 5, 8, 12, 16, 25, 40, 60, 100, 150, 250, 400]

# name, fuel species, fuel T (K), oxidizer species, ox T (K), O/F grid, default O/F, extra values
BIPROPS = [
    ("Kerolox", "RP-1", 298.15, "O2(L)", 90.17, [1.8, 2.0, 2.2, 2.4, 2.6, 2.8, 3.0, 3.2], 2.4,
     dict(fuelDensity=810, oxDensity=1141, lStar=1.1, coolantQuality=0.45, ignition="Pyrophoric",
          turbineGasCp=2400, turbineGasGamma=1.12, turbineGasTemp=1000)),
    ("Methalox", "CH4(L)", 111.64, "O2(L)", 90.17, [2.4, 2.8, 3.0, 3.3, 3.6, 3.9, 4.2], 3.6,
     dict(fuelDensity=422, oxDensity=1141, lStar=1.0, coolantQuality=0.35, ignition="Spark",
          turbineGasCp=3100, turbineGasGamma=1.15, turbineGasTemp=1000)),
    ("Hydrolox", "H2(L)", 20.27, "O2(L)", 90.17, [4.0, 4.5, 5.0, 5.5, 6.0, 6.5, 7.0], 5.5,
     dict(fuelDensity=70.8, oxDensity=1141, lStar=0.85, coolantQuality=1.0, ignition="Spark",
          turbineGasCp=9000, turbineGasGamma=1.36, turbineGasTemp=900)),
]
NTR_TC = [2300, 2500, 2700, 2900, 3100, 3300]
NTR_PC = [5, 10, 20, 35, 50, 70, 100]


def rocket(reac_names, temps, weights_fn, pc, tc=None):
    reac = cea.Mixture(reac_names)
    prod = cea.Mixture(reac_names, products_from_reactants=True)
    solver = cea.RocketSolver(prod, reactants=reac)
    sol = cea.RocketSolution(solver)
    w = weights_fn(reac)
    supar = [e for e in EPS if e > 1]
    if tc is None:
        hc = reac.calc_property(cea.ENTHALPY, w, np.array(temps)) / cea.R
        solver.solve(sol, w, pc, supar=supar, iac=True, hc=hc)
    else:
        solver.solve(sol, w, pc, supar=supar, iac=True, tc=tc)
    # points: 0 chamber, 1 throat, 2.. supersonic stations in EPS order
    n = sol.num_pts
    assert n == len(supar) + 2, n
    P = np.array(sol.P); isp = np.array(sol.Isp_vacuum) / G0; mach = np.array(sol.Mach)
    return dict(
        tc=sol.T[0], cstar=sol.c_star[0], mw=sol.MW[0], gamma=sol.gamma_s[0],
        isp=[isp[1]] + list(isp[2:]),            # eps = 1 is the throat
        pe=[P[1] / pc] + list(P[2:] / pc),
        mach=[mach[1]] + list(mach[2:]),
        gammaThroat=sol.gamma_s[1],
    )


def fmt(v, digits=5):
    return " ".join(f"{x:.{digits}g}" for x in v)


def main():
    cea.set_log_level(cea.LOG_NONE) if hasattr(cea, "set_log_level") else None
    lines = [
        "// Generated by tools/gen_propellants.py with NASA CEA " + str(getattr(cea, "__version__", "")) + " (shifting equilibrium, infinite-area combustor).",
        "// Do not edit by hand. Rows: one per (O/F, Pc). Columns per eps (see eps). isp = ideal vacuum Isp (s), pe = p/Pc, mach = local Mach.",
        "",
    ]
    for name, fuel, tf, ox, to, ofs, of_default, extra in BIPROPS:
        lines += ["PROCENG_PROPELLANT", "{", f"\tname = {name}", f"\tfuel = {fuel}", f"\toxidizer = {ox}", f"\tofDefault = {of_default}"]
        for k, v in extra.items():
            lines.append(f"\t{k} = {v}")
        lines.append(f"\tpc = {fmt(PC)}")
        lines.append(f"\teps = {fmt(EPS)}")
        lines.append(f"\tof = {fmt(ofs)}")
        for of in ofs:
            for pc in PC:
                wf = lambda reac, of=of: reac.of_ratio_to_weights(np.array([0.0, 1.0]), np.array([1.0, 0.0]), of)
                r = rocket([fuel, ox], [tf, to], wf, float(pc))
                lines += ["\tROW", "\t{",
                          f"\t\tof = {of}", f"\t\tpc = {pc}",
                          f"\t\ttc = {r['tc']:.1f}", f"\t\tcstar = {r['cstar']:.1f}", f"\t\tmw = {r['mw']:.4g}", f"\t\tgamma = {r['gamma']:.4g}",
                          f"\t\tisp = {fmt(r['isp'])}", f"\t\tpe = {fmt(r['pe'])}", f"\t\tmach = {fmt(r['mach'], 4)}", "\t}"]
            print(name, of, file=sys.stderr)
        lines += ["}", ""]

    # Nuclear thermal: pure H2 heated to a fixed chamber temperature (the "of" axis holds Tc in K).
    lines += ["PROCENG_PROPELLANT", "{", "\tname = NTR-H2", "\tfuel = H2(L)", "\tofAxis = Tc", "\tofDefault = 2700",
              "\tfuelDensity = 70.8", "\tlStar = 0.5", "\tcoolantQuality = 1.0", "\tignition = Reactor",
              f"\tpc = {fmt(NTR_PC)}", f"\teps = {fmt(EPS)}", f"\tof = {fmt(NTR_TC)}"]
    for tcK in NTR_TC:
        for pc in NTR_PC:
            r = rocket(["H2(L)"], [20.27], lambda reac: np.array([1.0]), float(pc), tc=float(tcK))
            lines += ["\tROW", "\t{", f"\t\tof = {tcK}", f"\t\tpc = {pc}",
                      f"\t\ttc = {r['tc']:.1f}", f"\t\tcstar = {r['cstar']:.1f}", f"\t\tmw = {r['mw']:.4g}", f"\t\tgamma = {r['gamma']:.4g}",
                      f"\t\tisp = {fmt(r['isp'])}", f"\t\tpe = {fmt(r['pe'])}", f"\t\tmach = {fmt(r['mach'], 4)}", "\t}"]
    lines += ["}", ""]

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote", os.path.normpath(OUT), file=sys.stderr)


if __name__ == "__main__":
    main()
